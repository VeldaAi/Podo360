/* ── Pricing: fixed USD (2026-08-19) ──
   No currency dropdown / FX anymore — prices are canonical in USD
   (PLAN_PRICES_USD). t() renders every plan price through fmtPlanPrice(),
   which always returns "US$ X.XX". getCur/setCur/refreshFx are kept as
   no-op stubs so legacy call sites (initI18n, lang buttons) don't break. */
const PLAN_PRICES_USD = { planEssPrice: 29.99, planProPrice: 49.99, planClinicPrice: 99.99 };
const PLAN_EXTRA_USD = 14.99;
function getCur(){ return 'USD'; }
function setCur(){ /* USD only — no-op */ }
function refreshFx(){ /* no-op: fixed USD prices */ }
function fmtPlanPrice(usd){
  const n = Number(usd) || 0;
  return 'US$ ' + n.toFixed(2);
}

/* ── storage helpers: prefer app.html lsGet/lsSet (localStorage+sessionStorage mirror),
      fall back to plain localStorage for other pages ── */
function _i18nStoreGet(k){
  try { if (typeof window.lsGet === 'function') { const v = window.lsGet(k); if (v !== null && v !== undefined) return v; } } catch(e){}
  try { const v = localStorage.getItem(k); if (v !== null) return v; } catch(e){}
  try { return sessionStorage.getItem(k); } catch(e){}
  return null;
}
function _i18nStoreSet(k, v){
  try { if (typeof window.lsSet === 'function') { window.lsSet(k, v); return; } } catch(e){}
  try { localStorage.setItem(k, v); } catch(e){}
  try { sessionStorage.setItem(k, v); } catch(e){}
}

/* ── lookup with dot-path support (cond.unha_encravada, pat.active...) ── */
function _i18nLookup(dict, key){
  if (!dict) return undefined;
  const parts = String(key).split('.');
  let o = dict;
  for (let i = 0; i < parts.length; i++){
    if (o == null) return undefined;
    o = o[parts[i]];
  }
  return o;
}

/* ── get stored lang (default pt) ── */
function getLang(){
  try {
    const v = _i18nStoreGet('podo360_lang');
    if (v === 'pt' || v === 'es' || v === 'en') return v;
  } catch(e){}
  return 'pt';
}

/* ── t(key, vars): dict[lang][key] → dict.pt[key] → key ── */
function t(key, vars){
  const lang = getLang();
  let v = _i18nLookup(window.I18N[lang], key);
  if (v === undefined) v = _i18nLookup(window.I18N.pt, key);
  if (v === undefined) v = key;
  // Pricing: plan price keys always render via fmtPlanPrice (fixed USD).
  if (typeof v === 'string') {
    if (PLAN_PRICES_USD[key] !== undefined) v = fmtPlanPrice(PLAN_PRICES_USD[key]);
    else if (key === 'planClinicExtra') v = v.replace(/(?:R\$\s*|US\$\s*)[\d.,]+/, fmtPlanPrice(PLAN_EXTRA_USD));
  }
  if (vars && typeof v === 'string'){
    for (const k in vars){
      v = v.split('{' + k + '}').join(String(vars[k]));
    }
  }
  return v;
}

/* ── localized dates ── */
function _i18nLocale(){
  const l = getLang();
  return l === 'pt' ? 'pt-BR' : l;
}
function fmtDate(isoOrStr){
  if (!isoOrStr) return '—';
  const dt = new Date(isoOrStr);
  if (isNaN(dt.getTime())) return String(isoOrStr).slice(0, 10);
  try { return dt.toLocaleDateString(_i18nLocale(), { day: '2-digit', month: 'short', year: 'numeric' }); }
  catch(e){ return dt.toDateString(); }
}
function fmtDateTime(isoOrStr){
  if (!isoOrStr) return '—';
  const dt = new Date(isoOrStr);
  if (isNaN(dt.getTime())) return String(isoOrStr).slice(0, 10);
  try { return dt.toLocaleString(_i18nLocale(), { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' }); }
  catch(e){ return dt.toString(); }
}

/* ── setLang: persist, apply attributes, title, pill, dispatch event ── */
function setLang(lang){
  if (lang !== 'pt' && lang !== 'es' && lang !== 'en') lang = 'pt';
  try { _i18nStoreSet('podo360_lang', lang); } catch(e){}
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t(el.getAttribute('data-i18n'));
    if (typeof v === 'string') el.innerHTML = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const v = t(el.getAttribute('data-i18n-ph'));
    if (typeof v === 'string') el.setAttribute('placeholder', v);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const v = t(el.getAttribute('data-i18n-aria'));
    if (typeof v === 'string') el.setAttribute('aria-label', v);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const v = t(el.getAttribute('data-i18n-title'));
    if (typeof v === 'string') el.setAttribute('title', v);
  });
  const tk = document.body && document.body.getAttribute('data-title-key');
  const tv = t(tk || 'title');
  if (typeof tv === 'string') document.title = tv;
  document.querySelectorAll('.lang-switch button[data-lang], .side-lang button[data-lang]').forEach(b => {
    b.classList.toggle('active', b.getAttribute('data-lang') === lang);
  });
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

/* ── initI18n: wire pills + apply stored lang. Auto-runs on DOMContentLoaded ── */
function initI18n(){
  document.querySelectorAll('.lang-switch button[data-lang], .side-lang button[data-lang]').forEach(b => {
    if (b.__podo360Wired) return;
    b.__podo360Wired = true;
    b.addEventListener('click', function(){ setLang(this.getAttribute('data-lang')); });
  });
  setLang(getLang());
}
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
